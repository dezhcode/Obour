# هر ایموجی پیش فرض باید فقط یک بار در کاتالوگ بیاید: جایگزینی متن بر
# اساس خود ایموجی انجام می شود، پس دو کلید با ایموجی یکسان یعنی یکی از
# آن ها هیچ وقت اعمال نمی شود. این بررسی هنگام بالا آمدن انجام می شود.
def duplicates() -> list[str]:
    """ایموجی هایی که در بیش از یک کلید تکرار شده اند."""
    seen: dict[str, str] = {}
    dupes: list[str] = []
    for key, (fallback, _t, _c) in CATALOG.items():
        base = fallback.replace("\ufe0f", "")
        if base in seen:
            dupes.append(f"{base} ({seen[base]} / {key})")
        else:
            seen[base] = key
    return dupes


# کش در حافظه تا هر پیام به دیتابیس نزند
_cache: dict[str, str] = {}
_loaded = False

SETTING_PREFIX = "emoji:"


async def load(db) -> None:  # noqa: ANN001
    """خواندن ایموجی های سفارشی از دیتابیس به کش."""
    global _loaded
    _cache.clear()
    try:
        rows = await db.fetchall(
            "SELECT key, value FROM settings WHERE key LIKE ?", (f"{SETTING_PREFIX}%",)
        )
        for r in rows:
            key = r["key"][len(SETTING_PREFIX) :]
            if r["value"]:
                _cache[key] = r["value"]
        _loaded = True
        log.info(
            "ایموجی های سفارشی بارگذاری شد: %s از %s", len(_cache), len(CATALOG)
        )
        dupes = duplicates()
        if dupes:
            # هشدار توسعه ای: کلید تازه ای با ایموجی تکراری اضافه شده
            log.warning("ایموجی تکراری در کاتالوگ: %s", ", ".join(dupes))
    except Exception:  # noqa: BLE001
        log.warning("بارگذاری ایموجی ناموفق بود، پیش فرض ها استفاده می شوند", exc_info=True)


async def set_emoji(db, key: str, emoji_id: str) -> None:  # noqa: ANN001
    """ثبت ایموجی پریمیوم برای یک کلید."""
    await db.set_setting(f"{SETTING_PREFIX}{key}", emoji_id)
    _cache[key] = emoji_id


async def reset_emoji(db, key: str) -> None:  # noqa: ANN001
    """بازگشت به ایموجی پیش فرض."""
    await db.set_setting(f"{SETTING_PREFIX}{key}", "")
    _cache.pop(key, None)


def default(key: str) -> str:
    """ایموجی پیش فرض یک کلید."""
    return CATALOG.get(key, ("❔", "", ""))[0]


def custom_id(key: str) -> str | None:
    """آیدی ایموجی سفارشی، اگر تنظیم شده باشد."""
    return _cache.get(key) or None


def text(key: str) -> str:
    """ایموجی برای استفاده در متن پیام.

    اگر سفارشی تنظیم شده باشد با تگ tg-emoji برمی گردد که در تلگرام
    به شکل ایموجی پریمیوم رندر می شود و در بقیه جاها به ایموجی
    پیش فرض برمی گردد.
    """
    fallback = default(key)
    eid = custom_id(key)
    if not eid:
        return fallback
    return f'<tg-emoji emoji-id="{eid}">{fallback}</tg-emoji>'


def titles_by_category() -> dict[str, list[tuple[str, str, str]]]:
    """فهرست ایموجی ها گروه بندی شده برای پنل ادمین."""
    out: dict[str, list[tuple[str, str, str]]] = {}
    for key, (emo, title, cat) in CATALOG.items():
        out.setdefault(cat, []).append((key, emo, title))
    return out
