_RLM = "\u200f"


def ensure_rtl(text_: str) -> str:
    """اطمینان از راست به چپ بودن پایه هر خط پیام.

    اگر خطی با یک حرف لاتین شروع شود - مثل کد پیگیری OB-XXXX، نام
    انگلیسی یک سرویس، یا یک لینک - و پیش از آن روی همان خط هیچ حرف
    قوی راست به چپی نباشد، بعضی کلاینت ها کل خط یا حتی کل پیام را
    چپ چین نمایش می دهند (چون اولین حرف قوی، جهت پایه را تعیین می کند
    و کدها داخل نشانه های ایزوله هم اگر تنها محتوای خط باشند این مشکل
    را حل نمی کنند). با گذاشتن یک نشانه راست به چپ نامرئی (RLM) در
    ابتدای هر خط، جهت پایه همیشه راست به چپ می ماند - بدون اینکه
    چیزی از ظاهر متن واقعی دیده شود یا تگ های HTML به هم بریزند.
    """
    if not text_ or not _i18n.is_rtl():
        return text_
    return "\n".join(
        line if (not line or line[0] == _RLM) else _RLM + line
        for line in text_.split("\n")
    )


def apply_emoji(text_: str) -> str:
    """جایگزینی ایموجی های متن با نسخه سفارشی ادمین.

    هر ایموجی پیش فرض که در پنل ادمین سفارشی شده باشد، با تگ tg-emoji
    جایگزین می شود. اگر هیچ ایموجی سفارشی تنظیم نشده باشد، متن دست نخورده
    برمی گردد (هزینه صفر).
    """
    import re

    from app import emoji as emo

    if not emo._cache:  # هیچ سفارشی سازی ای وجود ندارد
        return text_

    # اگر متن قبلا پردازش شده، دست نزن. بدون این شرط، اعمال دوباره
    # تگ ها را تودرتو می کند و تلگرام پیام را رد می کند.
    if "<tg-emoji" in text_:
        return text_

    # نگاشت ایموجی -> آیدی. اگر دو کلید ایموجی یکسان داشته باشند،
    # اولی برنده است تا تگ تودرتو ساخته نشود.
    mapping: dict[str, str] = {}
    for key, (fallback, _t, _c) in emo.CATALOG.items():
        eid = emo.custom_id(key)
        if eid and fallback not in mapping:
            mapping[fallback] = eid
    if not mapping:
        return text_

    # جایگزینی یک مرحله ای با regex تا متن خروجی دوباره پردازش نشود.
    # پس از هر ایموجی، تغییردهنده رنگ پوست و variation selector هم گرفته
    # می شوند تا مثلا 👋🏻 هم مثل 👋 تشخیص داده شود.
    modifiers = "[\U0001F3FB-\U0001F3FF\uFE0F]*"
    pattern = re.compile(
        "|".join(
            re.escape(e) + modifiers for e in sorted(mapping, key=len, reverse=True)
        )
    )

    def _sub(m: "re.Match[str]") -> str:
        whole = m.group(0)
        base = whole.rstrip("\U0001F3FB\U0001F3FC\U0001F3FD\U0001F3FE\U0001F3FF\uFE0F")
        eid = mapping.get(base) or mapping.get(whole)
        if not eid:
            return whole
        return f'<tg-emoji emoji-id="{eid}">{whole}</tg-emoji>'

    return pattern.sub(_sub, text_)


def rotate(options: tuple[str, ...]) -> str:
    """چرخش پیام (بخش ۱۳ سند): هر بار یک نسخه متفاوت."""
    return random.choice(options)


